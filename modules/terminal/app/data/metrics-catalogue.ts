export type SignalTone = 'bullish' | 'neutral' | 'caution' | 'bearish'
export type DataStatus = 'exchange' | 'public' | 'derived'

export interface Threshold {
  label: string
  value: string
  tone: SignalTone
}

export interface Indicator {
  title: string
  symbol: string
  category: string
  provider: string
  status: DataStatus
  unit: string
  formula: string
  reads: string
  sourcePath: string
  thresholds: Threshold[]
  icon: Component
}

type IndicatorInput = Omit<Indicator, 'thresholds' | 'icon'> & {
  thresholds?: Threshold[]
  icon?: Component
}

const neutralThresholds: Threshold[] = [
  { label: 'Low', value: 'Watch', tone: 'bullish' },
  { label: 'Normal', value: 'Base', tone: 'neutral' },
  { label: 'High', value: 'Risk', tone: 'caution' },
]

function metric(input: IndicatorInput): Indicator {
  return {
    thresholds: neutralThresholds,
    icon: Gauge,
    ...input,
  }
}

