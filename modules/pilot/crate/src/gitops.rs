        let (wt, _) = qs_mod_mcp::worktree::create_on_branch(&root, "quantpilot/clash", Some("main")).unwrap();
        let path = PathBuf::from(&wt.path);
        std::fs::write(path.join("a.txt"), "theirs\n").unwrap();
        commit(&path, "Change a in the worktree", None).unwrap();
        // Uncommitted work refuses the merge before anything happens.
        std::fs::write(path.join("b.txt"), "b\n").unwrap();
        assert!(merge_into_base(&root, &wt.path, "quantpilot/clash", "main").unwrap_err().contains("Commit or discard"));
